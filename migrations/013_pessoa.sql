-- Pessoa: o app passa a atender mais de uma pessoa, cada uma com os próprios dados.
-- Tudo o que já existe fica na pessoa 1. Nenhuma vaga é compartilhada: a mesma URL achada para duas
-- pessoas são duas linhas de vaga_encontrada, e as FKs compostas impedem que uma pessoa aplique ou
-- peça IA de uma vaga da outra.
-- Idempotente: pode ser aplicada de novo sem erro. Sem BEGIN/COMMIT e sem CONCURRENTLY.
-- DEPENDE de todas as anteriores (001–012): mexe em curriculo, perfil_busca, vaga_encontrada,
-- candidatura, pedido_ia, rotulo_ia e ia_lote_pausa.
-- `coleta_agendada` (008) fica global: o horário é do app. `pedido_ia.curriculo_id` e `curriculo_base_id`
-- seguem apontando para curriculo (id), que continua global; a conferência de que o currículo é da mesma
-- pessoa do pedido fica no serviço, não numa FK.

CREATE TABLE IF NOT EXISTS pessoa (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_exibicao  TEXT         NOT NULL CHECK (char_length(nome_exibicao) BETWEEN 1 AND 60),
    criada_em      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Dona dos dados de antes da 013. O nome real fica só no banco: o seed usa um rótulo neutro.
INSERT INTO pessoa (id, nome_exibicao) VALUES (1, 'Pessoa 1') ON CONFLICT (id) DO NOTHING;
SELECT setval(pg_get_serial_sequence('pessoa', 'id'), GREATEST(1, (SELECT max(id) FROM pessoa)));

-- 1. pessoa_id em tudo. O DEFAULT 1 só existe para preencher as linhas atuais; o passo 6 o remove, para
-- código que esquecer a pessoa falhar alto em vez de gravar na pessoa 1.
ALTER TABLE vaga_encontrada ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE candidatura     ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE pedido_ia       ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE rotulo_ia       ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE curriculo       ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE perfil_busca    ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);
ALTER TABLE ia_lote_pausa   ADD COLUMN IF NOT EXISTS pessoa_id BIGINT NOT NULL DEFAULT 1 REFERENCES pessoa (id);

-- 2. As FKs e o UNIQUE que dependem da PK antiga de vaga_encontrada (url) saem antes dela.
-- Os nomes são os que o Postgres deu na 002, 003 e 006; os novos têm outro nome, então uma segunda
-- execução não derruba os novos.
ALTER TABLE candidatura DROP CONSTRAINT IF EXISTS candidatura_vaga_url_fkey;
ALTER TABLE pedido_ia   DROP CONSTRAINT IF EXISTS pedido_ia_vaga_url_fkey;
ALTER TABLE rotulo_ia   DROP CONSTRAINT IF EXISTS rotulo_ia_vaga_url_fkey;
ALTER TABLE candidatura DROP CONSTRAINT IF EXISTS candidatura_vaga_url_key;

-- 3., 4. e 5. As PKs e UNIQUEs com a pessoa e as FKs compostas. Cada passo só age se ainda falta.
DO $$
BEGIN
    -- vaga_encontrada: PK (url) -> (pessoa_id, url).
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
        WHERE c.conrelid = 'vaga_encontrada'::regclass AND c.contype = 'p' AND a.attname = 'pessoa_id'
    ) THEN
        ALTER TABLE vaga_encontrada DROP CONSTRAINT vaga_encontrada_pkey;
        ALTER TABLE vaga_encontrada ADD CONSTRAINT vaga_encontrada_pkey PRIMARY KEY (pessoa_id, url);
    END IF;

    -- rotulo_ia: PK (vaga_url) -> (pessoa_id, vaga_url).
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
        WHERE c.conrelid = 'rotulo_ia'::regclass AND c.contype = 'p' AND a.attname = 'pessoa_id'
    ) THEN
        ALTER TABLE rotulo_ia DROP CONSTRAINT rotulo_ia_pkey;
        ALTER TABLE rotulo_ia ADD CONSTRAINT rotulo_ia_pkey PRIMARY KEY (pessoa_id, vaga_url);
    END IF;

    -- Uma candidatura por vaga de cada pessoa.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'candidatura'::regclass AND conname = 'candidatura_pessoa_vaga_key') THEN
        ALTER TABLE candidatura ADD CONSTRAINT candidatura_pessoa_vaga_key UNIQUE (pessoa_id, vaga_url);
    END IF;

    -- FKs compostas: a vaga tem que ser da mesma pessoa.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'candidatura'::regclass AND conname = 'candidatura_vaga_fkey') THEN
        ALTER TABLE candidatura ADD CONSTRAINT candidatura_vaga_fkey
            FOREIGN KEY (pessoa_id, vaga_url) REFERENCES vaga_encontrada (pessoa_id, url);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'pedido_ia'::regclass AND conname = 'pedido_ia_vaga_fkey') THEN
        ALTER TABLE pedido_ia ADD CONSTRAINT pedido_ia_vaga_fkey
            FOREIGN KEY (pessoa_id, vaga_url) REFERENCES vaga_encontrada (pessoa_id, url);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'rotulo_ia'::regclass AND conname = 'rotulo_ia_vaga_fkey') THEN
        ALTER TABLE rotulo_ia ADD CONSTRAINT rotulo_ia_vaga_fkey
            FOREIGN KEY (pessoa_id, vaga_url) REFERENCES vaga_encontrada (pessoa_id, url);
    END IF;

    -- perfil_busca e ia_lote_pausa: uma linha por pessoa. A PK passa de `id` para `pessoa_id` e a
    -- coluna `id` (com o CHECK id = 1) some.
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = 'perfil_busca'::regclass AND attname = 'id' AND NOT attisdropped) THEN
        ALTER TABLE perfil_busca DROP CONSTRAINT perfil_busca_pkey;
        ALTER TABLE perfil_busca ADD CONSTRAINT perfil_busca_pkey PRIMARY KEY (pessoa_id);
        ALTER TABLE perfil_busca DROP COLUMN id;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = 'ia_lote_pausa'::regclass AND attname = 'id' AND NOT attisdropped) THEN
        ALTER TABLE ia_lote_pausa DROP CONSTRAINT ia_lote_pausa_pkey;
        ALTER TABLE ia_lote_pausa ADD CONSTRAINT ia_lote_pausa_pkey PRIMARY KEY (pessoa_id);
        ALTER TABLE ia_lote_pausa DROP COLUMN id;
    END IF;
END $$;

-- 6. Sem o DEFAULT: quem esquecer a pessoa falha com NOT NULL.
ALTER TABLE vaga_encontrada ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE candidatura     ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE pedido_ia       ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE rotulo_ia       ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE curriculo       ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE perfil_busca    ALTER COLUMN pessoa_id DROP DEFAULT;
ALTER TABLE ia_lote_pausa   ALTER COLUMN pessoa_id DROP DEFAULT;

-- 7. Índices com a pessoa na frente (mesmos nomes de antes; só são refeitos se ainda não têm pessoa_id).
-- A fila do worker (pedido_ia_fila_prioridade_idx) e a dos presos (pedido_ia_rodando_idx) leem todas as
-- pessoas e continuam como estão.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'vaga_encontrada_novas_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS vaga_encontrada_novas_idx;
        CREATE INDEX vaga_encontrada_novas_idx ON vaga_encontrada (pessoa_id, primeira_vez_em DESC) WHERE vista_em IS NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'vaga_encontrada_primeira_vez_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS vaga_encontrada_primeira_vez_idx;
        CREATE INDEX vaga_encontrada_primeira_vez_idx ON vaga_encontrada (pessoa_id, primeira_vez_em DESC);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'vaga_encontrada_salva_em_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS vaga_encontrada_salva_em_idx;
        CREATE INDEX vaga_encontrada_salva_em_idx ON vaga_encontrada (pessoa_id, salva_em DESC) WHERE salva_em IS NOT NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'candidatura_aplicada_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS candidatura_aplicada_idx;
        CREATE INDEX candidatura_aplicada_idx ON candidatura (pessoa_id, aplicada_em DESC, id DESC);
    END IF;
    -- Um pedido ativo por (pessoa, vaga, tipo): pedir de novo devolve o ativo.
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'pedido_ia_ativo_uq' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS pedido_ia_ativo_uq;
        CREATE UNIQUE INDEX pedido_ia_ativo_uq ON pedido_ia (pessoa_id, vaga_url, tipo) WHERE estado IN ('pendente', 'rodando');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'pedido_ia_vaga_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS pedido_ia_vaga_idx;
        CREATE INDEX pedido_ia_vaga_idx ON pedido_ia (pessoa_id, vaga_url, tipo, id DESC);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = 'pedido_ia_lote_idx' AND indexdef LIKE '%(pessoa_id,%') THEN
        DROP INDEX IF EXISTS pedido_ia_lote_idx;
        CREATE INDEX pedido_ia_lote_idx ON pedido_ia (pessoa_id, criado_em) WHERE prioridade = 1;
    END IF;
END $$;
